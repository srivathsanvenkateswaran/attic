#!/usr/bin/env python3
"""Writes AtticUI/App/Strings.swift from the Android strings and the iOS overrides.

Run from the repo root: python3 ios/scripts/strings.py
The Android file stays the source; ios/scripts/strings-ios.txt adds or replaces keys, one per line
as `key = text` (plurals as `key.one = ...` and `key.other = ...`).
"""
import re
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ANDROID = ROOT / "app/src/main/res/values/strings.xml"
IOS = ROOT / "ios/scripts/strings-ios.txt"
OUT = ROOT / "ios/Packages/AtticModules/Sources/AtticUI/App/Strings.swift"


def unescape(text):
    text = text.strip()
    if len(text) >= 2 and text[0] == '"' and text[-1] == '"':
        text = text[1:-1]
    return text.replace("\\'", "'").replace('\\"', '"').replace("\\n", "\n").replace("\\@", "@").replace("\\?", "?")


def camel(key):
    parts = key.split("_")
    name = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    if name[0].isdigit():
        name = "s" + name
    return name


ARG = re.compile(r"%(?:(\d+)\$)?([sd@])")


def args_of(text):
    found = {}
    auto = 0
    for m in ARG.finditer(text):
        if m.group(1):
            index = int(m.group(1))
        else:
            auto += 1
            index = auto
        found[index] = "Int" if m.group(2) == "d" else "String"
    return [found[i] for i in sorted(found)]


def swift_literal(text):
    """A Swift string literal with %1$s etc. replaced by interpolations of a0, a1..."""
    auto = [0]

    def sub(m):
        if m.group(1):
            index = int(m.group(1))
        else:
            auto[0] += 1
            index = auto[0]
        return "\\(a%d)" % (index - 1)

    escaped = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    escaped = escaped.replace("%%", "\u0000")
    escaped = ARG.sub(sub, escaped)
    return '"' + escaped.replace("\u0000", "%") + '"'


strings = {}
plurals = {}
tree = ET.parse(ANDROID)
for node in tree.getroot():
    name = node.get("name")
    if node.tag == "string":
        strings[name] = unescape("".join(node.itertext()))
    elif node.tag == "plurals":
        plurals[name] = {item.get("quantity"): unescape("".join(item.itertext())) for item in node}

for line in IOS.read_text().splitlines():
    if not line.strip() or line.startswith("#"):
        continue
    key, _, text = line.partition(" = ")
    key = key.strip()
    if "." in key:
        base, quantity = key.split(".")
        plurals.setdefault(base, {})[quantity] = text
        strings.pop(base, None)
    else:
        strings[key] = text
        plurals.pop(key, None)

out = [
    "// Generated by ios/scripts/strings.py from app/src/main/res/values/strings.xml and",
    "// ios/scripts/strings-ios.txt. Do not edit; change those files and run the script.",
    "// Numbers that can pass 999 are passed as text, formatted by the caller (`grouped(_:)`).",
    "",
    "import Foundation",
    "",
    "/// Every user-facing string, named after its Android key in camel case (`song_count` is `S.songCount`).",
    "public enum S {",
]
for key in sorted(strings):
    text = strings[key]
    types = args_of(text)
    if types:
        params = ", ".join("_ a%d: %s" % (i, t) for i, t in enumerate(types))
        out.append("    public static func %s(%s) -> String { %s }" % (camel(key), params, swift_literal(text)))
    else:
        out.append("    public static let %s = %s" % (camel(key), swift_literal(text)))
for key in sorted(plurals):
    forms = plurals[key]
    other = forms.get("other", next(iter(forms.values())))
    one = forms.get("one", other)
    types = args_of(other) or args_of(one)
    # The count chooses the form; the arguments fill it (the first is usually the count as text).
    params = ", ".join(["count: Int"] + ["_ a%d: %s" % (i, t) for i, t in enumerate(types)])
    out.append(
        "    public static func %s(%s) -> String { count == 1 ? %s : %s }"
        % (camel(key), params, swift_literal(one), swift_literal(other))
    )
out += [
    "",
    "    /// A count with grouping, as the strings expect: 18460 gives \"18,460\".",
    "    public static func grouped(_ n: Int) -> String { n.formatted(.number.grouping(.automatic)) }",
    "}",
    "",
]
OUT.write_text("\n".join(out))
print("Wrote %s: %d strings, %d plurals" % (OUT.relative_to(ROOT), len(strings), len(plurals)))
